# Checks that the workbook build_workbook.py produces matches SCHEMA in
# apps-script/00_Config.gs, tab for tab and header for header.
#
# Why this exists: the Apps Script side reads and writes every column by header
# name, so a header the builder spells differently -- or forgets -- does not
# fail loudly. It fails as verifySchema() refusing to run, in the middle of a
# deployment, against a workbook you have already started filling in. Catching
# it here costs a few seconds of CI instead.
#
# The comparison is deliberately exact in both directions. verifySchema() can
# afford to treat an unexpected column as informational, because a human's own
# sheet may carry columns of their own; this workbook is generated by us, so
# anything in it that SCHEMA does not know about is a mistake in one file or
# the other. Order is not compared -- nothing addresses a column by index.
#
# Run: python scripts/check_schema.py

import re
import subprocess
import sys
import tempfile
from pathlib import Path

from openpyxl import load_workbook

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / 'apps-script' / '00_Config.gs'
BUILDER = ROOT / 'scripts' / 'build_workbook.py'

TAB_LINE = re.compile(r"^\s*'([^']+)':\s*\[")
NAME_LINE = re.compile(r"name:\s*'([^']+)'")


def parse_schema(text):
    """{tab: [header, ...]} from the SCHEMA block, in declaration order."""
    start = text.index('var SCHEMA = {')
    schema, tab = {}, None
    for line in text[start:].splitlines()[1:]:
        if line.startswith('};'):
            break
        tab_match = TAB_LINE.match(line)
        if tab_match:
            tab = tab_match.group(1)
            schema[tab] = []
            continue
        name_match = NAME_LINE.search(line)
        if name_match and tab:
            schema[tab].append(name_match.group(1))
    return schema


def built_headers(path):
    """{tab: [header, ...]} from row 1 of every tab in the built workbook."""
    wb = load_workbook(path, read_only=True)
    out = {}
    for ws in wb.worksheets:
        row = next(ws.iter_rows(min_row=1, max_row=1, values_only=True), ())
        out[ws.title] = [str(c).strip() for c in row if c is not None and str(c).strip()]
    wb.close()
    return out


def main():
    schema = parse_schema(CONFIG.read_text(encoding='utf-8'))
    if not schema:
        sys.exit('Could not parse SCHEMA out of %s' % CONFIG)

    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / 'check.xlsx'
        subprocess.run([sys.executable, str(BUILDER), str(out)], check=True,
                       stdout=subprocess.DEVNULL)
        built = built_headers(out)

    problems = []
    for tab, expected in schema.items():
        if tab not in built:
            problems.append('%s: SCHEMA declares this tab, the builder does not create it' % tab)
            continue

        # Folded the same way col_() folds them, so a case or spacing
        # difference that the live code would tolerate is not reported here.
        actual = built[tab]
        folded = [h.lower() for h in actual]
        for header in actual:
            if folded.count(header.lower()) > 1:
                problems.append('%s: builder writes "%s" twice; headerMap_ would keep only one'
                                % (tab, header))
        want = {h.lower(): h for h in expected}
        have = {h.lower(): h for h in actual}
        for key in sorted(set(want) - set(have)):
            problems.append('%s: SCHEMA expects "%s", the builder does not write it'
                            % (tab, want[key]))
        for key in sorted(set(have) - set(want)):
            problems.append('%s: builder writes "%s", SCHEMA does not list it'
                            % (tab, have[key]))

    # Tabs the builder adds that SCHEMA says nothing about (Settings, Budget,
    # Dashboard) are not an error -- the code never reads them by header.
    if problems:
        print('SCHEMA / builder mismatch:')
        for p in problems:
            print('  ' + p)
        print('\nFix whichever file is wrong: SCHEMA in apps-script/00_Config.gs,')
        print('or the header list in scripts/build_workbook.py.')
        sys.exit(1)

    checked = sum(len(v) for v in schema.values())
    print('SCHEMA OK - %d headers across %d tabs match the built workbook.'
          % (checked, len(schema)))


if __name__ == '__main__':
    main()
